"""GPU passthrough. A service labelled org.qrosetta.gpu=nvidia (cuQuantum) gets the CDI device
nvidia.com/gpu=all through a generated compose override, $XDG_STATE_HOME/qrosetta/compose.gpu.yaml,
when the host has a CDI specification for nvidia.com/gpu in a directory the engine reads (podman:
/etc/cdi and /var/run/cdi; docker: the CDISpecDirs its `info` lists, which it does only with CDI
enabled). Without one the service starts without a GPU, the server lists it as unavailable, and
`start` does not wait for it."""

import hashlib
import json
import os
import re

from qrosetta_cli import config as cfgmod

GPU_LABEL = "org.qrosetta.gpu"
DEVICE = "nvidia.com/gpu=all"
OVERRIDE_FILE = "compose.gpu.yaml"
PODMAN_SPEC_DIRS = ("/etc/cdi", "/var/run/cdi")
SPEC_STEP = "sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml"
_KIND = re.compile(r"""^kind\s*:\s*["']?nvidia\.com/gpu["']?\s*(#.*)?$""", re.MULTILINE)


def spec_dirs(engine):
    """The CDI specification directories the engine reads."""
    if getattr(engine, "name", "") == "podman":
        return PODMAN_SPEC_DIRS
    dirs = (getattr(engine, "info", None) or {}).get("CDISpecDirs") or []
    return tuple(d for d in dirs if isinstance(d, str))


def nvidia_spec(dirs):
    """The first CDI specification file in `dirs` that declares kind nvidia.com/gpu, or None."""
    for folder in dirs:
        try:
            names = sorted(os.listdir(folder))
        except OSError:
            continue
        for name in names:
            if not name.endswith((".yaml", ".yml", ".json")):
                continue
            path = os.path.join(folder, name)
            try:
                with open(path, encoding="utf-8", errors="replace") as fh:
                    text = fh.read(1 << 20)
            except OSError:
                continue
            if name.endswith(".json"):
                try:
                    found = json.loads(text).get("kind") == "nvidia.com/gpu"
                except (ValueError, AttributeError):
                    found = False
            else:
                found = bool(_KIND.search(text))
            if found:
                return path
    return None


def gpu_services(stack):
    """The compose services that need an NVIDIA GPU."""
    return sorted(name for name, svc in stack.services.items() if svc.labels.get(GPU_LABEL) == "nvidia")


def override_path(env):
    return os.path.join(cfgmod.qr_dir("state", env), OVERRIDE_FILE)


def override_text(project, services, spec):
    lines = [
        f"# Generated by qrosetta for compose project {project}: the NVIDIA GPU for the services",
        f"# that need one, from the CDI specification {spec}.",
        "services:",
    ]
    for name in services:
        lines += [f"  {json.dumps(name)}:", "    devices:", f"      - {DEVICE}"]
    return "\n".join(lines + [""])


def apply(engine, stack, env, find=None):
    """With a GPU service and an NVIDIA CDI specification, write the override and add it to the
    engine's compose files; records the specification on the stack (None without one)."""
    services = gpu_services(stack)
    stack.gpu_services = [stack.services[s].id for s in services]
    stack.gpu_spec = (find or nvidia_spec)(spec_dirs(engine)) if services else None
    if not stack.gpu_spec:
        return None
    text = override_text(stack.name, services, stack.gpu_spec)
    path = override_path(env)
    try:
        with open(path, encoding="utf-8") as fh:
            current = fh.read()
    except OSError:
        current = None
    if current != text:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    if path not in engine.files:
        engine.files.append(path)
    return hashlib.sha256(text.encode()).hexdigest()


def without_gpu_note(ids):
    return (
        f"{', '.join(ids)}: no CDI specification for an NVIDIA GPU on this host, so it runs without one "
        f"and is listed as unavailable (with an NVIDIA GPU: {SPEC_STEP}, then `qrosetta start` again)."
    )
