"""The CPU quota stack setting (spec §6.1). Where cgroup v2 does not delegate the cpu controller
to the user, a rootless engine cannot set compose's `cpus:` limits and `up` fails. `start
--no-cpu-quota` then runs every service without its CPU limit through a generated compose
override, $XDG_STATE_HOME/qrosetta/compose.no-cpu-quota.yaml, which resets only
deploy.resources.limits.cpus; memory limits stay. The choice is recorded as a stack setting,
so later commands give compose the same files. Runners record the quota they ran under
(cpu_environment.cpu_quota_cores, null without one); the server's timing caveats and the
self-test read it from there."""

import hashlib
import json
import os

from qrosetta_cli import config as cfgmod, localstack, output
from qrosetta_cli.errors import CliError, Exit
from qrosetta_cli.stack.explain import DELEGATE_DROPIN

OVERRIDE_FILE = "compose.no-cpu-quota.yaml"
RESET_MIN_COMPOSE = (2, 24)
FLAG_HINT = "qrosetta start -d --no-cpu-quota"
CGROUP_ROOT = "/sys/fs/cgroup"


def override_path(env):
    return os.path.join(cfgmod.qr_dir("state", env), OVERRIDE_FILE)


def override_text(project, services):
    """The override resetting the CPU limit of each of `services` (compose service names)."""
    lines = [
        f"# Generated by qrosetta for compose project {project}: removes the CPU limit",
        "# (deploy.resources.limits.cpus) of every service that has one; memory limits stay.",
        "# `qrosetta start --cpu-quota` stops using this file.",
    ]
    if not services:
        return "\n".join(lines + ["services: {}", ""])
    lines.append("services:")
    for name in sorted(services):
        lines += [
            f"  {json.dumps(name)}:",
            "    deploy:",
            "      resources:",
            "        limits:",
            "          cpus: !reset null",
        ]
    return "\n".join(lines + [""])


def apply(engine, stack, enabled, env):
    """With the quota off, write the override and add it to the engine's compose files; its
    sha256, or None with the quota on."""
    stack.cpu_quota = enabled
    if enabled:
        stack.cpu_override_sha256 = None
        return None
    version = getattr(engine, "compose_version", None)
    if version is not None and version < RESET_MIN_COMPOSE:
        raise CliError(
            f"Starting without the CPU quota needs Docker Compose {RESET_MIN_COMPOSE[0]}."
            f"{RESET_MIN_COMPOSE[1]} or later (`!reset` in an override file); this is "
            f"{version[0]}.{version[1]}.",
            Exit.ENGINE,
            "compose_too_old",
            hint="qrosetta doctor",
        )
    text = override_text(stack.name, [s for s, svc in stack.services.items() if svc.cpus is not None])
    path = override_path(env)
    try:
        with open(path, encoding="utf-8") as fh:
            current = fh.read()
    except OSError:
        current = None
    if current != text:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    if path not in engine.files:
        engine.files.append(path)
    stack.cpu_override_sha256 = hashlib.sha256(text.encode()).hexdigest()
    return stack.cpu_override_sha256


def wanted(ctx):
    """(enabled, source): --no-cpu-quota / --cpu-quota, else the recorded stack setting, else
    config lifecycle.cpu_quota, else on."""
    flag = ctx.opt("cpu_quota")
    if flag is not None:
        return flag, "--cpu-quota" if flag else "--no-cpu-quota"
    enabled, _, source = localstack.cpu_quota(ctx.env, ctx.cfg)
    return enabled, source


def _read(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return None


def _exists(path):
    return os.path.exists(path)


def user_controllers(read=None, exists=None, uid=None):
    """The string "v1" on cgroup v1, else the controllers delegated to this user's systemd instance (None
    when its cgroup.controllers file cannot be read)."""
    uid = os.getuid() if uid is None else uid
    if not (exists or _exists)(f"{CGROUP_ROOT}/cgroup.controllers"):
        return "v1"
    text = (read or _read)(f"{CGROUP_ROOT}/user.slice/user-{uid}.slice/user@{uid}.service/cgroup.controllers")
    return None if text is None else set(text.split())


def check_host(engine, enabled, read=None, exists=None, uid=None):
    """Refuse before compose does: a rootless engine on cgroup v2 without the memory controller,
    or without the cpu controller while the CPU quota is on."""
    if not engine.rootless or (uid is None and not hasattr(os, "getuid")):
        return
    have = user_controllers(read, exists, uid)
    if have in ("v1", None):
        return
    if "memory" not in have:
        raise CliError(
            "The cgroup memory controller is not delegated to your user, so the memory limit of each "
            "service cannot be set. Delegate the controllers with this drop-in, then reboot:\n" + DELEGATE_DROPIN,
            Exit.ENGINE,
            "memory_controller_missing",
            hint="qrosetta doctor",
        )
    if enabled and "cpu" not in have:
        raise CliError(
            "The cgroup cpu controller is not delegated to your user, so compose cannot set the CPU "
            "limit of each service (1.0 CPU per runner) and `up` would fail. Delegate the controllers "
            "with this drop-in, then reboot:\n" + DELEGATE_DROPIN + "\nOr start without the CPU "
            "quota: results then record cpu_quota_cores null and carry the 'no CPU quota' timing "
            "caveat, and the self-test warns.",
            Exit.ENGINE,
            "cpu_controller_missing",
            hint=FLAG_HINT,
        )


def record(env, project, enabled, sha256):
    """Record the setting `start` used for `project`; returns it. Nothing is written for a
    project that never ran without the quota."""
    old = localstack.stack_settings(env, project)
    if enabled and "cpu_quota" not in old:
        return {"cpu_quota": True, "since": None}
    since = old.get("since") if old.get("cpu_quota") == enabled else output.utc_now()
    values = {
        "cpu_quota": enabled,
        "since": since,
        "override": None if enabled else override_path(env),
        "override_sha256": sha256,
    }
    kept = {k: v for k, v in old.items() if k not in values}
    if {**kept, **values} != old:
        localstack.write_stack_settings(env, project, {**kept, **values})
    return values


def describe_off(since=None):
    return (
        f"CPU quota off{f' since {since}' if since else ''}: services run without their compose CPU limit "
        "(memory limits stay); results record cpu_quota_cores null and carry the 'no CPU quota' timing "
        "caveat, so their timings are not comparable with runs under the quota. "
        "`qrosetta start -d --cpu-quota` restores it."
    )


def block(stack, env):
    """The CPU quota object of start's and status's JSON."""
    since = localstack.stack_settings(env, stack.name).get("since")
    return {
        "enabled": stack.cpu_quota,
        "since": None if stack.cpu_quota else since,
        "override": None if stack.cpu_quota else override_path(env),
        "override_sha256": stack.cpu_override_sha256,
    }
