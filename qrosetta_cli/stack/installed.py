"""Installed mode (no checkout): the compose file generated from the package's release manifest
in $XDG_STATE_HOME/qrosetta, or a refusal while the release's images are not published."""

import json
import os
import re

from qrosetta_cli import __version__, config as cfgmod, manifest as mf
from qrosetta_cli.errors import CliError, Exit

SOURCE_ROUTE = (
    "git clone https://github.com/SeQuSoS-Project/QRosetta && cd QRosetta && ./qrosetta build && ./qrosetta start"
)
COMPOSE_NAME = "compose.yaml"
_DEFAULTED = re.compile(r"^\$\{[A-Za-z_][A-Za-z0-9_]*:-(.+)\}$")


def state_dir(env=None):
    return cfgmod.qr_dir("state", env)


def refuse_unpublished(manifest):
    release = (manifest or {}).get("platform_version") or __version__
    why = (
        "this package carries no release manifest"
        if manifest is None
        else "its release manifest names no published image digests"
    )
    raise CliError(
        f"The container images of Quantum Rosetta {release} are not published ({why}), so this "
        "installed qrosetta has no stack to start or inspect. Run Quantum Rosetta from a source "
        "checkout instead; it builds the images on this machine.",
        Exit.INCOMPATIBLE,
        "images_not_published",
        hint=SOURCE_ROUTE,
    )


def compose_document(manifest, local=None):
    """The compose file of the release: each published service as the release recorded it, with
    its image by digest, or by the tag in `local` ({service id: tag}) for an image `images load`
    put there; services without a published image are left out."""
    refs = mf.published_refs(manifest)
    local = local or {}
    doc = dict(manifest["compose"])
    doc["services"] = {
        svc["compose_service"]: dict(svc["compose"], image=local.get(sid) or refs[sid])
        for sid, svc in manifest["services"].items()
        if sid in refs
    }
    return doc


def _file_sources(doc):
    """The `file` of every secret and the `source` of every long-syntax bind mount."""
    for secret in (doc.get("secrets") or {}).values():
        yield (secret or {}).get("file") or ""
    for svc in (doc.get("services") or {}).values():
        for vol in (svc or {}).get("volumes") or []:
            if isinstance(vol, dict) and vol.get("type") == "bind":
                yield vol.get("source") or ""


def _placeholders(doc, directory):
    """Empty files at the relative default paths of file secrets and bind mounts, as the checkout
    carries them."""
    for path in _file_sources(doc):
        match = _DEFAULTED.match(path)
        path = match.group(1) if match else path
        if not path or path.startswith("$") or os.path.isabs(path):
            continue
        target = os.path.normpath(os.path.join(directory, path))
        if not target.startswith(directory + os.sep):
            continue
        os.makedirs(os.path.dirname(target), mode=0o700, exist_ok=True)
        if not os.path.exists(target):
            open(target, "x", encoding="utf-8").close()


def write_compose(manifest, directory, local=None):
    """Write the compose file (JSON, which YAML reads) into `directory` through a temporary file
    in the same directory; return the directory."""
    directory = os.path.abspath(directory)
    os.makedirs(directory, mode=0o700, exist_ok=True)
    doc = compose_document(manifest, local)
    text = (
        f"# Generated by qrosetta {__version__} from the release manifest of Quantum Rosetta "
        f"{manifest.get('platform_version', '?')}; rewritten by every command that opens the stack.\n"
        + json.dumps(doc, indent=2, sort_keys=False)
        + "\n"
    )
    path = os.path.join(directory, COMPOSE_NAME)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(tmp, path)
    _placeholders(doc, directory)
    return directory


def require_published(manifest=None):
    """The package's release manifest, or a refusal while it names no published images."""
    manifest = mf.load() if manifest is None else manifest
    if not mf.images_published(manifest):
        refuse_unpublished(manifest)
    return manifest


def prepare(env=None, manifest=None):
    """(project directory, manifest) for installed mode: the state directory with the compose
    file written, or a refusal while the images are not published."""
    manifest = require_published(manifest)
    return write_compose(manifest, state_dir(env)), manifest


def loaded_images(engine, manifest):
    """{service id: tag} for each published service whose image by digest is absent while the
    tag `images load` gives it holds an image with an id this release recorded for it."""
    from qrosetta_cli.stack import project as st

    refs = mf.published_refs(manifest)
    release = manifest.get("platform_version") or ""
    tags = {sid: mf.loaded_tag(engine.project, manifest["services"][sid]["compose_service"], release) for sid in refs}
    present = st.find_images(engine, list(refs.values()))
    tagged = st.find_images(engine, list(tags.values()))
    local = {}
    for sid, tag in tags.items():
        img = tagged.get(tag)
        if refs[sid] not in present and img is not None and mf.image_id_key(img.id) in mf.release_ids(manifest, sid):
            local[sid] = tag
    return local


def localise(engine, manifest):
    """Rewrite the generated compose file so that loaded release images are used where the image
    by digest is absent; return {service id: tag} of those services."""
    local = loaded_images(engine, manifest)
    if local:
        write_compose(manifest, engine.project_dir, local)
    return local
