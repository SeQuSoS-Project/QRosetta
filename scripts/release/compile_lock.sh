#!/usr/bin/env bash
# Regenerates a service's requirements.lock with sha256 hashes, resolved by pip inside the service's
# base image. The current lock is the constraint set, so a pin moves only when requirements.txt, the
# base image's Python or an edit to the lock forces it; packages no longer required drop out.
# Usage: scripts/release/compile_lock.sh <service-dir> <base-image@sha256:...>   (ENGINE=docker|podman)
set -euo pipefail

cd "$(dirname "$0")/../.."
dir=${1:?service directory, e.g. rosetta-api}
base=${2:?base image, pinned by digest}
engine=${ENGINE:-podman}
pip_tools=7.6.2
case "$base" in *@sha256:*) ;; *) echo "base image must be pinned by digest: $base" >&2; exit 2 ;; esac

mkdir -p "${TMPDIR:-$HOME/.tmp}"
work=$(mktemp -d "${TMPDIR:-$HOME/.tmp}/compile-lock.XXXXXX")
trap 'rm -rf "$work"' EXIT
cp "$dir/requirements.txt" "$work/requirements.in"
sed -e 's/#.*//' -e 's/[[:space:]]*\\$//' -e '/^[[:space:]]*--hash/d' -e '/^[[:space:]]*$/d' \
  "$dir/requirements.lock" > "$work/previous-requirements.lock"

"$engine" run --rm -v "$work:/work:Z" -w /work -e PIP_DISABLE_PIP_VERSION_CHECK=1 \
  -e PIP_ROOT_USER_ACTION=ignore --entrypoint sh "$base" -c "
    set -e
    python -m venv /opt/lock
    /opt/lock/bin/pip install -q pip-tools==$pip_tools
    /opt/lock/bin/pip-compile -q --generate-hashes --allow-unsafe --strip-extras --no-header \
      --constraint previous-requirements.lock --output-file out.txt requirements.in
    { python -V; /opt/lock/bin/pip --version; } > versions.txt"

python_version=$(sed -n 's/^Python //p' "$work/versions.txt")
pip_version=$(sed -n 's/^pip \([^ ]*\).*/\1/p' "$work/versions.txt")
{
  echo "# Generated by scripts/release/compile_lock.sh in $base"
  echo "# (Python $python_version, pip $pip_version, pip-tools $pip_tools), constrained by the previous lock."
  echo "# qrosetta_commons is not listed; the Dockerfile installs shared/ separately."
  echo "# Install with: pip install --require-hashes -r requirements.lock"
  cat "$work/out.txt"
} > "$dir/requirements.lock"
echo "wrote $dir/requirements.lock" >&2
