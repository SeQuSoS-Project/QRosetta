"""Markdown evidence file of the requalification harness."""

import json
from pathlib import Path

import compare


def _py(v):
    return f"{v[0]}.{v[1]}" if v else "?"


def _ms(v):
    return "—" if v is None else f"{v:.3f}"


def _verdict(ev):
    if ev.get("prepare", {}).get("stop"):
        return "STOPPED: " + "; ".join(ev["prepare"]["stop"])
    if "corpus" not in ev:
        return "corpus not run"
    diffs = ev["corpus"]["differences"]
    real = [d for d in diffs if d["class"] != "known_jitter"]
    cases = sum(v["cases"] for v in ev["corpus"]["by_kind"].values())
    if not diffs:
        return f"outputs identical on all {cases} corpus cases"
    if not real:
        return f"{len(diffs)} of {cases} cases differ only within the known statevector jitter"
    return f"{len(real)} of {cases} corpus cases differ in output fields"


def _timing_rows(ev):
    lines = ["| Case | Old comp ms | New comp ms | Old sim ms | New sim ms | Old total ms | New total ms "
             "| New/old total | Samples old/new | CPUs | Peak RSS MiB old/new | Outputs equal |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name in sorted(ev.get("timing", {})):
        cell = ev["timing"][name]
        o, n = cell.get("old", {}), cell.get("new", {})
        ratio = (n["total_ms"] / o["total_ms"]) if o.get("total_ms") and n.get("total_ms") else None
        same = (o.get("distinct_outputs") == 1 and n.get("distinct_outputs") == 1
                and o.get("output_digest") == n.get("output_digest"))
        rss = f"{o.get('peak_rss_mib') or 0:.1f} / {n.get('peak_rss_mib') or 0:.1f}"
        lines.append(f"| {name.removesuffix('.json')} | {_ms(o.get('compilation_ms'))} | {_ms(n.get('compilation_ms'))} "
                     f"| {_ms(o.get('simulation_ms'))} | {_ms(n.get('simulation_ms'))} | {_ms(o.get('total_ms'))} "
                     f"| {_ms(n.get('total_ms'))} | {'—' if ratio is None else f'{ratio:.3f}'} "
                     f"| {o.get('samples')}/{n.get('samples')} | {sorted(set(o.get('cpus', [])) | set(n.get('cpus', [])))} "
                     f"| {rss} | {'yes' if same else 'NO'} |")
    return lines


def _row(ev):
    prep, c = ev["prepare"], ev["corpus"]
    parts = ", ".join(f"{k} {v['cases']}" for k, v in c["by_kind"].items())
    timing = "; ".join(
        f"{name.removesuffix('.json')} total {_ms(cell['old'].get('total_ms'))} → {_ms(cell['new'].get('total_ms'))} ms"
        for name, cell in sorted(ev.get("timing", {}).items()) if "old" in cell and "new" in cell)
    loads = [r[k] for r in ev.get("timing_rounds", []) if r["accepted"] for k in ("load_before", "load_after")]
    scan = ev.get("scan", {})
    scan_text = ""
    if scan:
        f = {k: v["counts"]["fixed"] for k, v in scan.items()}
        scan_text = (f" Trivy fixed CRITICAL/HIGH {f['old'].get('CRITICAL', 0)}/{f['old'].get('HIGH', 0)} → "
                     f"{f['new'].get('CRITICAL', 0)}/{f['new'].get('HIGH', 0)}.")
    timing_text = ""
    if timing:
        timing_text = (f" Timing pinned to CPU {ev['args'].get('cpu')}, "
                       f"{len([r for r in ev.get('timing_rounds', []) if r['accepted']])} alternated rounds"
                       f"{f', load {min(loads):.1f}–{max(loads):.1f}' if loads else ''}: {timing}.")
    sizes = ev.get("images", {})
    size_text = (f" Image {sizes['old']['size'] / 1e6:.0f} → {sizes['new']['size'] / 1e6:.0f} MB." if sizes else "")
    rule = (f"`{ev['svc']['dir']}/Dockerfile` runs `{prep['new_base'].split('@')[0]}` by digest (Python "
            f"{_py(prep['new_python'])}), with the apt snapshot and a hash-pinned lock from `compile_lock.sh`. "
            f"Changing its base needs `scripts/requalify/requalify.sh {ev['service']}` with identical outputs.")
    evidence = (f"{ev['started'][:10]}: Python {_py(prep['old_python'])} → {_py(prep['new_python'])} at one commit. "
                f"{_verdict(ev)} ({parts}); self-test "
                f"{'identical' if ev.get('selftest', {}).get('old') == ev.get('selftest', {}).get('new') else 'differs'}; "
                f"{len(prep.get('lock_moves', []))} lock pins moved.{timing_text}{scan_text}{size_text}")
    return f"| {ev['service']} image Python | {rule} | {evidence} |"


def write(path, ev):
    prep = ev.get("prepare", {})
    svc = ev["svc"]
    out = [f"# Requalification: {ev['service']} ({svc['dir']})", "",
           f"Generated by `scripts/requalify/requalify.sh` at commit `{ev['git_sha']}`, "
           f"{ev['started']} to {ev.get('finished', '?')}.", "",
           f"**Result:** {_verdict(ev)}.", ""]
    if prep:
        out += ["## Candidate", "",
                f"- Base: {', '.join(f'`{b}`' for b in prep.get('old_bases', []))} (Python {_py(prep.get('old_python'))}) "
                f"→ `{prep.get('new_base')}` (Python {_py(prep.get('new_python'))}, glibc "
                f"{'.'.join(map(str, prep.get('glibc') or []))}).",
                f"- SDK packages (`declare_sdk_packages`): {', '.join(prep.get('sdk_packages', [])) or 'none'}."]
        for change in prep.get("dockerfile_changes", []):
            out.append(f"- Dockerfile: {change}.")
        for item in prep.get("manual", []):
            out.append(f"- Not rewritten, needs a hand edit: `{item}`.")
        missing = [r for r in prep.get("wheel_check", []) if not r["new_wheel"]]
        out.append(f"- Wheel check of {len(prep.get('wheel_check', []))} pinned packages on PyPI: "
                   + ("every pin has a build for the new Python." if not missing else
                      "no build for the new Python: " + ", ".join(
                          f"{r['name']}=={r['version']} (old Python: {'wheel' if r['old_wheel'] else 'no wheel'}"
                          f"{', sdist' if r['sdist'] else ''}{', nearest with a build ' + r['nearest'] if r['nearest'] else ''})"
                          for r in missing) + "."))
        if prep.get("replaced"):
            out.append("- Pins moved to the nearest release with a build: "
                       + ", ".join(f"{k} → {v}" for k, v in prep["replaced"].items()) + ".")
        for name, why in (prep.get("added") or {}).items():
            out.append(f"- Added to requirements.txt: {name}=={why}.")
        if prep.get("relaxed"):
            out.append("- Pins dropped from the constraints (`--relax`): " + ", ".join(prep["relaxed"]) + ".")
        moves = prep.get("lock_moves", [])
        out += ["", f"Lock pins that moved ({len(moves)}):", ""]
        if moves:
            out += ["| Package | Old | New |", "|---|---|---|"]
            out += [f"| {m['name']} | {m['old'] or '—'} | {m['new'] or '—'} |" for m in moves]
        else:
            out.append("none.")
        out.append("")
    if "images" in ev:
        env = ev.get("environment", {})
        out += ["## Images", "", "| Image | ID | Python | Size MB | Built | Build s |", "|---|---|---|---|---|---|"]
        for label, img in ev["images"].items():
            out.append(f"| `{img['tag']}` | {img['id'][:12]} | {env.get(label, {}).get('python', '?')} "
                       f"| {img['size'] / 1e6:.1f} | "
                       f"{'yes' if img['rebuilt'] else 'reused (same context)'} | {img['build_sec']} |")
        out.append("")
        imports = ev.get("imports", {})
        if imports:
            for label in ("old", "new"):
                failed = sorted(k for k, v in imports.get(label, {}).items() if v is not None)
                out.append(f"Import check, {label} image: `main` and {len(imports.get(label, {})) - 1} SDK "
                           f"module(s) ({', '.join(k for k in imports.get(label, {}) if k != 'main')}); "
                           + ("all import." if not failed else "failing: " + ", ".join(failed) + "."))
            out.append("")
    if "corpus" in ev:
        c = ev["corpus"]
        out += ["## Corpus", "",
                "Fixed seeds (circuits 20261002, payloads 20261028). Runners: each case through "
                "`run_with_uniform_measurement(process_run[_measured], payload)`, the function the CLI path "
                "and the isolated child call (warm-up + one timed run); compilers: `process_compile(payload)`, "
                "each case in a child forked from that process. One process per image, `--network none`.", "",
                "| Part | Cases | Identical | Different | Known jitter | Errors (old) |", "|---|---|---|---|---|---|"]
        for kind, v in c["by_kind"].items():
            out.append(f"| {kind} | {v.get('cases', 0)} | {v.get('identical', 0)} | {v.get('different', 0)} "
                       f"| {v.get('known_jitter', 0)} | {v.get('errors_old', 0)} |")
        out += ["", compare.exclusion_text(), ""]
        if c["differences"]:
            out += [f"Differences ({len(c['differences'])}, first 40):", ""]
            for d in c["differences"][:40]:
                extra = ""
                if "infidelity" in d:
                    extra = f", 1-F {d['infidelity']:.3g}, max |Δ| {d['max_amplitude_delta']:.3g}"
                out.append(f"- `{d['id']}` level {d.get('level')} pre {d.get('pre')}: {', '.join(d['keys'])} "
                           f"({d['class']}{extra})")
                for key, val in (d.get("values") or {}).items():
                    out.append(f"  - {key}: old `{val['old']}` new `{val['new']}`")
            out.append("")
        cli = ev.get("cli_check", [])
        bad = [r for r in cli if r["keys"]]
        out += [f"CLI path check: {len({r['id'] for r in cli})} cases, in each image, also run through "
                f"`main.py --endpoint ... --payload-file` in a process each; " + ("outputs equal the driver's in every case." if not bad else
                                           f"{len(bad)} differ: " + "; ".join(f"{r['image']} {r['id']}: {r['keys']}" for r in bad)),
                ""]
        st = ev.get("selftest", {})
        out += ["Self-test (`main.py --self-test`): " + ("identical output in both images." if st.get("old") == st.get("new")
                                                         else "output differs."), "", "```", st.get("new", "").strip(), "```", ""]
        if st.get("old") != st.get("new"):
            out += ["Old image:", "```", st.get("old", "").strip(), "```", ""]
        out += ["Provenance fields that differ (expected with a new Python; not counted as output differences):", ""]
        for key, values in c["provenance"].items():
            for v in values[:3]:
                out.append(f"- `{key}` in {v['cases']} cases: old `{json.dumps(v['old'])}` → new `{json.dumps(v['new'])}`")
        if not c["provenance"]:
            out.append("- none.")
        moves = ev.get("distribution_moves", [])
        env = ev.get("environment", {})
        out += ["", f"Installed distributions (importlib.metadata) that differ between the images, Python "
                f"{env.get('old', {}).get('python')} → {env.get('new', {}).get('python')} ({len(moves)}):", ""]
        out += [f"- {m['name']}: {m['old'] or '—'} → {m['new'] or '—'}" for m in moves] or ["- none."]
        out.append("")
    if "timing" in ev:
        args = ev["args"]
        out += ["## Timing", "",
                f"Each cell: `main.py --endpoint` in its own process (warm-up, then timing_repeats={args['repeats']}), "
                f"{args['rounds']} rounds, image order alternated, container `--network none --cpus 1.0 --memory 1g`, "
                f"`taskset -c {args['cpu']}` and `QROSETTA_CPU_AFFINITY={args['cpu']}`; medians over all samples of "
                "the accepted rounds. Statevector circuits as in `scripts/adapter_paths/time_paths.py`; measured: "
                "8200 shots, seed 1.", ""]
        out += _timing_rows(ev)
        out += ["", "| Round | Attempt | Order | Load before | Load after | CPU busy % (pinned + siblings) | Accepted |",
                "|---|---|---|---|---|---|---|"]
        for r in ev.get("timing_rounds", []):
            out.append(f"| {r['round']} | {r['attempt']} | {'→'.join(r['order'])} | {r['load_before']:.2f} "
                       f"| {r['load_after']:.2f} | {r['cpu_busy_percent']} | {'yes' if r['accepted'] else 'no'} |")
        out.append("")
    if "scan" in ev:
        out += ["## Trivy", "", f"`{next(iter(ev['scan'].values()))['trivy']}`, `--scanners vuln`, no ignore file.", "",
                "| Image | Fixed C/H/M/L | All C/H/M/L/U |", "|---|---|---|"]
        for label, s in ev["scan"].items():
            f, a = s["counts"]["fixed"], s["counts"]["all"]
            out.append(f"| {label} | {f.get('CRITICAL', 0)}/{f.get('HIGH', 0)}/{f.get('MEDIUM', 0)}/{f.get('LOW', 0)} "
                       f"| {a.get('CRITICAL', 0)}/{a.get('HIGH', 0)}/{a.get('MEDIUM', 0)}/{a.get('LOW', 0)}/{a.get('UNKNOWN', 0)} |")
        out.append("")
    if "corpus" in ev and prep:
        out += ["## Proposed CLAUDE.md §3.4 row", "", "| Decision | Rule | Evidence |", "|---|---|---|", _row(ev), ""]
    if "removed" in ev:
        out += ["## Cleanup", "", "Removed by ID: " + (", ".join(i[:12] for i in ev["removed"]) or "nothing") + ".", ""]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n")
